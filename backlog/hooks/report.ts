// What the "отчёт" button hands Claude: how a report for a client about one
// finished task reads. Plain data, no `$`, so tests read it directly.
//
// The answer comes back in the chat, in one code block, which has its own copy
// button, so nothing here draws a card. Claude writes it from the whole
// conversation and the project's git history; the rules keep it a person's
// message to a person: short, plain, first person, no code talk, no dashes.

import type { BacklogItem } from '../types'

/** The mark every report starts with. */
export const OPENER = '🪴'

const RULES = [
  'Как писать:',
  '1. Я пишу клиенту сам, поэтому от первого лица: "я", а не "мы". Род бери из того, как я пишу о себе в разговоре. Если не видно, строй фразы без рода: "готово", "теперь работает".',
  '2. Человек человеку, как в мессенджере: простые слова, короткие предложения, мало запятых. Лучше два предложения, чем одно длинное. Без канцелярита вроде "в рамках", "осуществлено", "был реализован", "данный", "следует отметить", "таким образом".',
  `3. Без шаблонов нейросети: без вступлений ("Рад сообщить", "Хочу отметить"), без восклицаний, без смайликов (кроме ${OPENER} в начале), без вывода-резюме в конце, без "надеюсь, это поможет", без пересказа очевидного.`,
  '4. Без технических подробностей: никаких названий файлов, функций, веток, коммитов, команд и библиотек. Пиши, что изменилось для клиента и его людей и что им теперь делать или не делать.',
  '5. Никаких длинных тире. Где нужно, точка или запятая. Кавычки только прямые: "пример".',
  '6. Без жирного, заголовков с решётками и другой разметки.',
  '7. Если нужно перечислить несколько вещей, каждая идёт отдельной строкой, между ними пустая строка. Без "-" и "•" в начале и без точки в конце, если пункт короткий и понятный. Один пункт пиши обычным предложением.',
  '8. Коротко: два или три абзаца, в каждом не больше двух предложений. Если мыслей больше, оформи их пунктами по правилу 7.',
].join('\n')

// Made up on purpose: it shows the voice and the layout, not facts to reuse.
const EXAMPLE = [
  `${OPENER} v1.4.0`,
  '',
  'Разобрался, почему письма не доходили до клиентов. Часть уходила на старый адрес, который вы поменяли в сентябре.',
  '',
  'Я поправил адрес и отправил застрявшие письма заново. Их было 14.',
  '',
  'Что теперь работает:',
  '',
  'Новые письма уходят сразу',
  '',
  'Список отправленных открывается за секунду',
  '',
  'Пока не меняйте адрес в настройках, я проверяю ещё один случай.',
].join('\n')

/** What the button hands Claude as the person's own words, for a finished task. */
export function reportPrompt(item: Pick<BacklogItem, 'id' | 'text'>): string {
  return [
    `Напиши клиенту отчёт о сделанной задаче [${item.id}]: ${item.text}`,
    'Опирайся только на то, что реально сделано: на этот разговор и на историю git проекта (посмотри git log и найди коммиты по этой задаче). Ничего не придумывай, числа бери только из данных. Если следов работы по задаче не нашёл или не уверен, не пиши наугад: скажи это одной фразой и спроси меня.',
    `Первая строка: ${OPENER} и версия проекта вида v1.2.3 из поля version в package.json. Если файла нет, возьми последний тег git. Если версии нигде нет, поставь только ${OPENER}. Дальше пустая строка и сам текст.`,
    'В тексте: что сделано и что изменилось для людей. Если что-то не доделано или лучше подождать, скажи прямо. Если нужно что-то от клиента, одной фразой в конце.',
    RULES,
    `Пример тона, он выдуманный, факты из него не бери:\n\n${EXAMPLE}`,
    'Ответь только отчётом в одном блоке кода ```text, чтобы я скопировал его одной кнопкой. До и после блока ничего не пиши.',
  ].join('\n\n')
}
